"""Write schemas/genome.v1.json and lib/genome.ts from the Pydantic models.

Run: python -m relicon.genome.export
"""
from __future__ import annotations

import json
from pathlib import Path

from ..config import REPO_ROOT
from .models import SCHEMA_VERSION, Genome


def json_schema() -> dict:
    s = Genome.model_json_schema()
    s["$id"] = f"https://relicon.ai/schemas/{SCHEMA_VERSION}.json"
    s["title"] = "Relicon Creative Genome v1"
    return s


def _ts(t: dict, defs: dict) -> str:
    if "$ref" in t:
        return t["$ref"].split("/")[-1]
    if "enum" in t:
        return " | ".join(json.dumps(v) for v in t["enum"])
    if "const" in t:
        return json.dumps(t["const"])
    if "anyOf" in t:
        return " | ".join(_ts(x, defs) for x in t["anyOf"])
    ty = t.get("type")
    if ty == "array":
        inner = _ts(t.get("items", {}), defs)
        return f"Array<{inner}>"
    if ty == "object":
        ap = t.get("additionalProperties")
        return f"Record<string, {_ts(ap, defs) if isinstance(ap, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(ty, "unknown")


def typescript(schema: dict) -> str:
    defs = schema.get("$defs", {})
    out = ["// GENERATED by `python -m relicon.genome.export`. Do not edit.",
           f"// Source: schemas/{SCHEMA_VERSION}.json", ""]
    items = list(defs.items()) + [("Genome", schema)]
    for name, d in items:
        out.append(f"export interface {name} {{")
        req = set(d.get("required", []))
        for prop, t in d.get("properties", {}).items():
            tag = t.get("x-relicon-tag")
            note = f"  // {tag}" if tag else ""
            out.append(f"  {prop}{'' if prop in req else '?'}: {_ts(t, defs)};{note}")
        out.append("}\n")
    return "\n".join(out)


def main() -> None:
    schema = json_schema()
    sp = REPO_ROOT / "schemas" / f"{SCHEMA_VERSION}.json"
    sp.parent.mkdir(exist_ok=True)
    sp.write_text(json.dumps(schema, indent=2) + "\n")
    tp = REPO_ROOT / "lib" / "genome.ts"
    tp.write_text(typescript(schema))
    print(f"wrote {sp.relative_to(REPO_ROOT)} and {tp.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
